test("when section IDs collide then it fails before changing files", (t) => {
  const fixture = createFixture();
  t.after(() => removeFixture(fixture));
  const componentsDirectory = path.join(fixture.sourceDirectory, "components");
  const readDirectory = fs.readdirSync;
  const readFile = fs.readFileSync;
  fs.readdirSync = ((directory: fs.PathLike, options?: unknown) => {
    const entries = readDirectory(
      directory,
      options as { withFileTypes: true },
    );
    if (directory !== componentsDirectory) {
      return entries;
    }
    return [
      ...entries,
      { name: "hero.tsx", isDirectory: () => false, isFile: () => true },
    ];
  }) as typeof fs.readdirSync;
  fs.readFileSync = ((filePath: fs.PathOrFileDescriptor, options?: unknown) =>
    filePath === path.join(componentsDirectory, "hero.tsx")
      ? "export const hero = () => <div />;\n"
      : readFile(
          filePath,
          options as { encoding: "utf8" },
        )) as typeof fs.readFileSync;
  try {
    assert.throws(
      () =>
        migrateBuiltInTemplate({
          templateId: "example",
          rootDirectory: fixture.root,
          apply: true,
          write: () => {},
        }),
      /Duplicate section ID/,
    );
  } finally {
    fs.readdirSync = readDirectory;
    fs.readFileSync = readFile;
  }
  assert.equal(fs.existsSync(fixture.sourceDirectory), true);
  assert.equal(fs.existsSync(fixture.libraryDirectory), false);
});

test("when source or destination validation fails then it changes no files", (t) => {
  const cases: ValidationCase[] = [
    {
      name: "a required file is missing",
      setup: (fixture) =>
        fs.rmSync(path.join(fixture.sourceDirectory, "template.json")),
      error: /missing/,
    },
    {
      name: "a component directory is nested",
      setup: (fixture) =>
        fs.mkdirSync(
          path.join(fixture.sourceDirectory, "components", "shared"),
        ),
      error: /Nested component directories/,
    },
    {
      name: "a component imports outside the component directory",
      components: {
        "Hero.tsx":
          'import { value } from "../shared";\nexport const Hero = () => <div>{value}</div>;\n',
      },
      error: /Relative import leaves/,
    },
    {
      name: "a component already exports config",
      components: {
        "Hero.tsx":
          "export const Hero = () => <div />;\nexport const config = {};\n",
      },
      error: /already exports config/,
    },
    {
      name: "a component lacks its matching named export",
      components: { "Hero.tsx": "export const Other = () => <div />;\n" },
      error: /must have a named export/,
    },
    {
      name: "the metadata JSON is invalid",
      setup: (fixture) =>
        fs.writeFileSync(
          path.join(fixture.sourceDirectory, "template.json"),
          "{",
        ),
      error: /Could not read legacy template metadata/,
    },
    {
      name: "the default layout references a missing section",
      layout: {
        content: [
          { type: "Missing", props: {} },
          { type: "MainContent", props: {} },
        ],
      },
      error: /references missing section Missing/,
    },
    {
      name: "the destination already has a real library",
      libraryFiles: { "library.json": "{}\n" },
      error: /destination is not fresh/,
    },
  ];

  for (const testCase of cases) {
    const fixture = createFixture(testCase);
    t.after(() => removeFixture(fixture));
    testCase.setup?.(fixture);

    assert.throws(
      () =>
        migrateBuiltInTemplate({
          templateId: "example",
          rootDirectory: fixture.root,
          apply: true,
          write: () => {},
        }),
      testCase.error,
      testCase.name,
    );
    assert.equal(fs.existsSync(fixture.sourceDirectory), true, testCase.name);
    assert.equal(
      fs.existsSync(path.join(fixture.libraryDirectory, "layouts", "example")),
      false,
      testCase.name,
    );
  }
});

test("when the Café and Coffee Shop template is inspected then it remains unchanged", () => {
  const starterRoot = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    "..",
  );
  const cafeDirectory = path.join(
    starterRoot,
    "src",
    "registry",
    "yext-cafe-and-coffee-shop",
  );
  const templatePath = path.join(cafeDirectory, "template.json");
  const original = fs.readFileSync(templatePath, "utf8");

  assert.equal(
    fs.existsSync(path.join(cafeDirectory, "defaultLayout.json")),
    true,
  );
  assert.equal(
    fs
      .readdirSync(path.join(cafeDirectory, "components"))
      .filter((name) => name.endsWith(".tsx")).length > 0,
    true,
  );
  assert.equal(fs.readFileSync(templatePath, "utf8"), original);
});
