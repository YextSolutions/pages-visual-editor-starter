import { migrateBuiltInTemplate } from "./migrateBuiltInTemplate.js";

const TODO_DISPLAY_NAME = "TODO: Add a display name.";
const TODO_DESCRIPTION = "TODO: Add a description.";

type Fixture = {
  root: string;
  sourceDirectory: string;
  libraryDirectory: string;
};

type FixtureOptions = {
  template?: Record<string, unknown>;
  layout?: unknown;
  components?: Record<string, string>;
  libraryFiles?: Record<string, string>;
};

type ValidationCase = FixtureOptions & {
  name: string;
  setup?: (fixture: Fixture) => void;
  error: RegExp;
};

/** Creates one isolated legacy-template fixture for a conversion test. */
const createFixture = ({
  template = {},
  layout = { content: [{ type: "Hero", props: {} }] },
  components = { "Hero.tsx": "export const Hero = () => <div />;\n" },
  libraryFiles = {},
}: FixtureOptions = {}): Fixture => {
  const root = fs.mkdtempSync(
    path.join(os.tmpdir(), "section-library-migration-"),
  );
  const sourceDirectory = path.join(root, "src", "registry", "example");
  const componentsDirectory = path.join(sourceDirectory, "components");
  fs.mkdirSync(componentsDirectory, { recursive: true });
  fs.writeFileSync(
    path.join(sourceDirectory, "template.json"),
    JSON.stringify({
      displayName: "Example Template",
      description: "Example description",
      previewImageUrl: "https://example.com/preview.png",
      previewSiteUrl: "",
      verticals: ["RETAIL"],
      purposes: ["LOCATION"],
      isBuiltIn: true,
      ...template,
    }),
  );
  fs.writeFileSync(
    path.join(sourceDirectory, "defaultLayout.json"),
    JSON.stringify(layout),
  );
  for (const [fileName, content] of Object.entries(components)) {
    const filePath = path.join(componentsDirectory, fileName);
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, content);
  }
  for (const [relativePath, content] of Object.entries(libraryFiles)) {
    const filePath = path.join(root, "src", "library", relativePath);
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, content);
  }
  return {
    root,
    sourceDirectory,
    libraryDirectory: path.join(root, "src", "library"),
  };
};

const removeFixture = (fixture: Fixture): void => {
  fs.rmSync(fixture.root, { recursive: true, force: true });
};

test("when dry run then it reports the conversion without changing files", (t) => {
  const fixture = createFixture({
    libraryFiles: {
      ".generated/libraryConfig.tsx":
        "/** THIS FILE IS GENERATED BY THE SECTION LIBRARY PLUGIN */\n",
    },
  });
  t.after(() => removeFixture(fixture));
  const output: string[] = [];

  migrateBuiltInTemplate({
    templateId: "example",
    rootDirectory: fixture.root,
    apply: false,
    write: (message) => output.push(message),
  });

  assert.equal(fs.existsSync(fixture.sourceDirectory), true);
  assert.equal(
    fs.readFileSync(
      path.join(fixture.libraryDirectory, ".generated", "libraryConfig.tsx"),
      "utf8",
    ),
    "/** THIS FILE IS GENERATED BY THE SECTION LIBRARY PLUGIN */\n",
  );
  assert.match(output.join("\n"), /Dry run: no files changed/);
  assert.match(output.join("\n"), /Manual follow-up work/);
});

test("when apply then it creates the Section Library and removes the legacy template", (t) => {
  const fixture = createFixture();
  t.after(() => removeFixture(fixture));

  migrateBuiltInTemplate({
    templateId: "example",
    rootDirectory: fixture.root,
    apply: true,
    write: () => {},
  });

  assert.equal(fs.existsSync(fixture.sourceDirectory), false);
  assert.deepEqual(
    JSON.parse(
      fs.readFileSync(
        path.join(fixture.libraryDirectory, "library.json"),
        "utf8",
      ),
    ),
    {
      schemaVersion: 1,
      id: "example",
      displayName: "Example Template",
      description: "Example description",
    },
  );
  assert.deepEqual(
    JSON.parse(
      fs.readFileSync(
        path.join(
          fixture.libraryDirectory,
          "layouts",
          "example",
          "metadata.json",
        ),
        "utf8",
      ),
    ),
    {
      id: "example",
      displayName: "Example Template",
      previewImageUrl: "https://example.com/preview.png",
      vertical: "RETAIL",
      purpose: "LOCATION",
      pageSetType: "ENTITY",
    },
  );
  assert.deepEqual(
    JSON.parse(
      fs.readFileSync(
        path.join(
          fixture.libraryDirectory,
          "layouts",
          "example",
          "defaultLayout.json",
        ),
        "utf8",
      ),
    ),
    { content: [{ type: "Hero", props: {} }] },
  );
  assert.match(
    fs.readFileSync(
      path.join(fixture.libraryDirectory, "sections", "Hero.tsx"),
      "utf8",
    ),
    /export const config: SectionConfig = \{\n  displayName: "TODO: Add a section display name\."/,
  );
});

